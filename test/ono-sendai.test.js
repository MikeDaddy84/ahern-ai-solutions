const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const { createClient } = require('@libsql/client');
const { createStore } = require('../lib/portal-auth');
const { createRouter } = require('../lib/portal');

test('Ono-Sendai pairs a single owner and publishes bounded, read-only headers', async t => {
  const client = createClient({url:'file::memory:'});
  const store = createStore(client);
  t.after(() => client.close());
  const app = express();
  app.use(express.json(), createRouter({storeProvider:()=>store}));
  const server = app.listen(0,'127.0.0.1');
  await new Promise(resolve => server.once('listening',resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const origin = 'http://127.0.0.1:' + server.address().port;
  async function session(name,role) {
    const email = name+'@example.test', password = 'example-test-password';
    await store.provision({email,password,workspace:name,name,role});
    const cookie = await store.login(email,password);
    return {cookie:'ahern_portal='+cookie,'x-csrf-token':(await store.session(cookie)).csrf,origin};
  }
  const owner = await session('first','owner'), other = await session('second','owner'), member = await session('member','employee');
  const get = (path,headers) => fetch(origin+path,{headers});
  const post = (path,headers,body) => fetch(origin+path,{method:'POST',headers:{...headers,'content-type':'application/json'},body:JSON.stringify(body)});
  const pair = headers => post('/api/portal/ono-sendai/pair',headers,{});
  assert.doesNotMatch(await (await get('/portal',owner)).text(), /data-widget="ono-sendai"/);
  assert.equal((await pair(member)).status,403);
  assert.equal((await pair({...owner,'x-csrf-token':'wrong'})).status,403);
  const {token} = await (await pair(owner)).json();
  const now = new Date().toISOString();
  const message = {sender:'Example',subject:'<script>mailSubject</script>',received:now,important:true,unread:true,body:'private message body'};
  const payload = {version:1,updated:now,accounts:[{state:'idle',last_ok:now,unread:1,messages:[message,{...message,important:false}]}]};
  const push = (value,body) => post('/api/portal/ono-sendai-feed',{authorization:'Bearer '+value},body);
  assert.equal((await push('bad',payload)).status,401);
  assert.equal((await push(token,{version:1})).status,400);
  assert.equal((await push(token,payload)).status,204);
  assert.match(await (await get('/portal',owner)).text(), /data-widget="ono-sendai"/);
  assert.doesNotMatch(await (await get('/portal',other)).text(), /data-widget="ono-sendai"/);
  const path = '/api/portal/overview/ono-sendai';
  assert.equal((await get(path,{})).status,401);
  assert.equal((await get(path,member)).status,403);
  assert.equal((await get(path,other)).status,503);
  const result = await (await get(path,owner)).json();
  assert.equal(result.messages.length,1);
  assert.equal(result.messages[0].body,undefined);
  const page = await (await get('/portal/ono-sendai',owner)).text();
  assert.match(page,/Mail accounts/);
  assert.match(await (await get('/portal/ono-sendai/account/pilot',owner)).text(),/&lt;script&gt;mailSubject/);
  assert.doesNotMatch(page,/private message body/);
  const crypto = require('node:crypto');
  const secret = crypto.randomBytes(32).toString('hex');
  const fingerprint = crypto.createHash('sha256').update(secret).digest('hex');
  const device = {authorization:'Bearer '+token,'x-ono-device':secret};
  const mail = '/api/portal/ono-sendai/mail';
  const connect = '/api/portal/ono-sendai/device';
  const poll = '/api/portal/ono-device/poll';
  const reply = '/api/portal/ono-device/result';
  assert.equal((await post(mail,owner,{action:'folders'})).status,403);
  assert.equal((await post(connect,member,{fingerprint})).status,403);
  assert.equal((await post(connect,{...owner,'x-csrf-token':''},{fingerprint})).status,403);
  assert.equal((await post(connect,owner,{fingerprint})).status,204);
  const enroll = '/api/portal/ono-sendai/enroll';
  assert.match(await (await get('/portal/ono-sendai',owner)).text(),/Add Account/);
  assert.match(await (await get('/portal/ono-sendai/add-account',owner)).text(),/id="mail-enroll"/);
  assert.equal((await get('/portal/ono-sendai/add-account',member)).status,403);
  assert.equal((await post(enroll,other,{action:'setupKey'})).status,403);
  assert.equal((await post(enroll,member,{action:'setupKey'})).status,403);
  assert.equal((await post(enroll,{...owner,'x-csrf-token':''},{action:'setupKey'})).status,403);
  assert.equal((await post(mail,owner,{action:'connectAccount'})).status,400);
  assert.equal((await post(enroll,owner,{action:'connectAccount',provider:'gmail',address:'a@example.test',sealed:'bad'})).status,400);
  const sealed = Buffer.alloc(256,1).toString('base64');
  const enrollment = {action:'connectAccount',provider:'gmail',address:'a@example.test',sealed};
  const pendingSetup = post(enroll,owner,{...enrollment,extra:'ignored'});
  const setupJob = await (await post(poll,device,{enrollment:true})).json();
  assert.deepEqual(setupJob.command,enrollment);
  assert.equal((await post(reply,device,{id:setupJob.id,value:{id:'mail-abc'}})).status,204);
  assert.deepEqual(await (await pendingSetup).json(),{id:'mail-abc'});
  const a = {...payload.accounts[0],id:'pilot',address:'first@example.test',provider:'gmail'};
  const b = {...a,id:'second',address:'second@example.test',unread:7};
  const pending = {...b,id:'pending',address:'pending@example.test',last_ok:null,unread:null,messages:[]};
  const multi = {version:2,updated:now,accounts:[a,b,pending]};
  assert.equal((await push(token,{...multi,accounts:[a,a]})).status,400);
  assert.equal((await push(token,multi)).status,204);
  const landing = await (await get('/portal/ono-sendai',owner)).text();
  assert.match(landing,/second@example.test/);
  assert.doesNotMatch(landing,/id="composer"/);
  const overview = await (await get(path,owner)).json();
  assert.equal(overview.unread,8);
  assert.deepEqual(overview.accounts.map(a=>a.unread),[1,7,null]);
  assert.deepEqual(overview.messages.map(m=>m.account).sort(),[a.address,b.address].sort());
  assert.match(await (await get('/portal/ono-sendai/account/second',owner)).text(),/data-account="second"/);
  assert.equal((await get('/portal/ono-sendai/account/second',other)).status,404);
  assert.equal((await post(mail,owner,{action:'folders',account:'unknown'})).status,403);
  assert.equal((await post(mail,other,{action:'folders'})).status,403);
  assert.equal((await post(poll,{authorization:'Bearer '+token},{})).status,401);
  assert.equal((await post(poll,{...device,'x-ono-device':'0'.repeat(64)},{})).status,403);
  const request = post(mail,owner,{action:'folders',account:'second'});
  const job = await (await post(poll,device,{accountRouting:true})).json();
  assert.equal(job.command.account,'second');
  assert.equal(job.command.action,'folders');
  assert.equal((await post(reply,device,{id:job.id,value:{folders:[]}})).status,204);
  assert.deepEqual(await (await request).json(),{folders:[]});
  assert.equal((await post(reply,device,{id:job.id,value:{folders:[]}})).status,404);
  assert.equal((await pair(owner)).status,200);
  assert.equal((await post(poll,device,{})).status,403);
  assert.equal((await post(mail,owner,{action:'folders'})).status,403);
  assert.equal((await push(token,payload)).status,403);
});
