// Prints the unit-economics model behind the investor one-pager.
//
//   node scripts/unit-economics.js
//
// Why this lives in the repo rather than in a spreadsheet: the hardware half of
// the model is not independent of the site. Build prices, the handling fee, and
// the platform table all come out of public/pricing.js, and that file is
// repriced every quarter. A spreadsheet copy of those numbers is wrong the day
// after the next repricing and nobody notices, because nothing connects them.
// This reads the live engine, so a repricing moves the model in the same commit.
//
// Everything else — the funnel, the calendar, the engagement mix — is an
// assumption, and every one of them is a named constant below. They are guesses
// about a business that has not yet invoiced a customer. Argue with them here,
// not in the document.
//
// The one-pager is a separate artifact and is NOT generated by this script;
// figures are carried across by hand when the model changes. If you change a
// constant here, the document is stale until someone updates it.

const fs = require('fs');
const path = require('path');

// pricing.js is a browser file — it assigns to `window` and expects nothing
// else — so it runs here against a stand-in object rather than being required.
function loadPricing() {
  const src = fs.readFileSync(path.join(__dirname, '..', 'public', 'pricing.js'), 'utf8');
  const shim = {};
  new Function('window', src)(shim);
  return shim.AHERN_PRICING;
}

const P = loadPricing();
const p = P.parts;

// ---------------------------------------------------------------- assumptions

const CARD = 0.029;   // card processing, charged on the WHOLE invoice
const LLM  = 0.05;    // LLM/API cost, software lines only
const HOUR = 150;     // founder hour, used to cost acquisition time

// Total working hours a month — all in, not billable. Overhead comes out of
// this before anything reaches a customer.
const CAPACITY = [120, 140, 160];

const SALES_SHARE = 0.22;

// Overhead is NOT a flat share of hours, and modelling it as one was wrong.
//
// Staying current in a field that moves quarterly, keeping the tooling alive,
// and general business admin cost roughly the same whether the week is half
// full or full. Quoting, invoicing and onboarding scale with customers, not
// with capacity. A flat 25% share was defensible at 70 hours a month, where it
// came to 17 hours. Carried to a genuine full-time 160, the same share asserts
// 40 hours a month of bookkeeping, which is not a real number — and every hour
// it invents comes straight out of delivery.
//
// Splitting it fixed the error and had a consequence worth noticing: at
// full-time capacity, overhead shrinks as a share, delivery capacity grows, and
// the funnel has to work harder to keep up with it.
const OVERHEAD_BASE_HOURS = 12;      // fixed monthly: learning, tooling, admin
const OVERHEAD_PER_CUSTOMER = 1.5;   // quoting, invoicing, onboarding

// Funnel. 14 hours of outreach and calls to land one customer at a 15% close
// rate, scaling inversely with the close rate. This is the single input that
// decides whether the business is short of customers or short of hours.
const HOURS_PER_CUSTOMER_AT_15 = 14;
const CLOSE_RATES = [0.15, 0.25];

const ATTACH = 0.40;                 // share of customers who take a retainer
const CHURN = 0.05;                  // monthly
const LIFE = 1 / CHURN;              // 20 months
const RETAINER = { price: 897, hours: 1.5, gp: 897 * (1 - LLM - CARD) };
const FIXED_MONTHLY = 55;            // tooling and hosting; there is no floor to defend

// Representative builds, priced by the live engine rather than typed in here.
const BUILDS = {
  gaming:  { label: 'Gaming PC (1440p)', hours: 6,
             b: { track: 'gaming', cpu: p.cpu.balanced8, gpu: p.gpu.game1440, ram: p.ram.gb32,
                  storage: p.storage.nvme2tb, cooling: p.cooling.air, case: p['case'].glassRgb } },
  creator: { label: 'Creator workstation', hours: 8,
             b: { track: 'creative', cpu: p.cpu.editor, gpu: p.gpu.creatorVideo, ram: p.ram.gb64,
                  storage: p.storage.nvme4tb, cooling: p.cooling.quiet, case: p['case'].workstation } },
  localai: { label: 'Local AI build (70B-class)', hours: 16,
             b: { track: 'ai', cpu: p.cpu.highCore, gpu: p.gpu.aiFlagship, ram: p.ram.gb128,
                  storage: p.storage.nvme4tb, cooling: p.cooling.airAi, case: p['case'].serverQuiet } },
  spark:   { label: 'AI appliance (DGX Spark)', hours: 7,   b: { appliance: P.appliances.dgxSpark } },
  strix:   { label: 'AI appliance (Ryzen AI Max+)', hours: 6, b: { appliance: P.appliances.strixHalo } }
};

// What one new customer buys first, weighted. This is the biggest lever on
// every blended figure and it is a guess — replace it with real data as soon as
// there is any.
const MIX = [
  { what: 'AI Quickstart',       w: 0.50, rev: 1250, hours: 7,   gp: 1250 * (1 - LLM - CARD) },
  { what: 'Automation Sprint',   w: 0.12, rev: 4500, hours: 17,  gp: 4500 * (1 - LLM - CARD) },
  { what: 'Front Door site',     w: 0.06, rev: 8000, hours: 35,  gp: 8000 * (1 - CARD) },
  { what: 'Gaming / creator PC', w: 0.20, hours: 7,   hw: ['gaming', 'creator'] },
  { what: 'AI appliance',        w: 0.08, hours: 6.5, hw: ['strix', 'spark'] },
  { what: 'Local AI build',      w: 0.04, hours: 16,  hw: ['localai'] }
];

// ------------------------------------------------------------------- the model

// Gross profit on hardware is handling plus labor, less the card fee on the
// whole invoice. Components and platform pass through at cost and contribute
// nothing but the handling charged on them — which is why the card fee matters
// so much here: it is levied on money that was never margin to begin with.
function hardware(key) {
  const d = BUILDS[key];
  const e = P.estimate(d.b);
  const gp = [0, 1].map(i => e.handling[i] + e.laborTotal - CARD * e.total[i]);
  return {
    label: d.label, hours: d.hours, total: e.total,
    gp: gp.map(Math.round),
    gm: [0, 1].map(i => gp[i] / e.total[i]),
    perHour: gp.map(g => Math.round(g / d.hours))
  };
}

function blend() {
  const mid = a => (a[0] + a[1]) / 2;
  let rev = 0, hrs = 0, gp = 0;
  const rows = MIX.map(m => {
    let r = m.rev, g = m.gp;
    if (m.hw) {
      const hs = m.hw.map(hardware);
      r = hs.reduce((s, h) => s + mid(h.total), 0) / hs.length;
      g = hs.reduce((s, h) => s + mid(h.gp), 0) / hs.length;
    }
    rev += m.w * r; hrs += m.w * m.hours; gp += m.w * g;
    return { what: m.what, w: m.w, rev: Math.round(r), gp: Math.round(g), hours: m.hours };
  });
  return { rows, rev, hrs, gp };
}

// Delivery hours one steady-state customer eventually consumes: the first
// engagement, plus the retainer they may carry for its whole life. This is the
// number a calendar has to hold, not the project.
function loadPerCustomer() {
  return blend().hrs + ATTACH * LIFE * RETAINER.hours;
}

// The outreach share at which demand and delivery bind at the same moment.
// Below it the calendar idles; above it, work is sold that cannot be delivered.
//
// This now depends on total hours, through the fixed overhead base: a bigger
// week dilutes a constant 12 hours, so more of the calendar is available to
// deliver with and the funnel has to be pushed harder to fill it.
function optimalSalesShare(close, H, base) {
  base = base == null ? OVERHEAD_BASE_HOURS : base;
  const hpc = HOURS_PER_CUSTOMER_AT_15 * (0.15 / close);
  return (hpc * (1 - base / H)) / (loadPerCustomer() + OVERHEAD_PER_CUSTOMER + hpc);
}

function capacity(H, close, base, salesShare) {
  base = base == null ? OVERHEAD_BASE_HOURS : base;
  salesShare = salesShare == null ? SALES_SHARE : salesShare;
  const b = blend();
  const sales = H * salesShare;
  const hoursPerCustomer = HOURS_PER_CUSTOMER_AT_15 * (0.15 / close);

  // Two ceilings: the funnel produces this many customers a month, and the
  // calendar can carry this many. Revenue is set by the lower of the two —
  // reporting the higher one is how a model promises undeliverable work.
  const demandCust = sales / hoursPerCustomer;

  // Delivery capacity and overhead are mutually dependent now: each customer
  // brings their own admin, which eats the very hours available to serve them.
  // Solving c = (H - sales - base - perCustomer*c) / load for c:
  const deliveryCust = (H - sales - base) / (loadPerCustomer() + OVERHEAD_PER_CUSTOMER);
  const custPerMo = Math.min(demandCust, deliveryCust);

  const overhead = base + OVERHEAD_PER_CUSTOMER * custPerMo;
  const deliveryCap = H - sales - overhead;
  const retainers = custPerMo * ATTACH * LIFE;
  const revMo = custPerMo * b.rev + retainers * RETAINER.price;
  const gpMo = custPerMo * b.gp + retainers * RETAINER.gp - FIXED_MONTHLY;
  return {
    H, close, sales, deliveryCap, overhead,
    deliveryUsed: custPerMo * b.hrs + retainers * RETAINER.hours,
    custPerMo, retainers,
    binding: demandCust <= deliveryCust ? 'demand' : 'delivery',
    revYr: revMo * 12, gpYr: gpMo * 12,
    recurringShare: (retainers * RETAINER.price) / revMo
  };
}

function ltv() {
  const b = blend();
  return { entry: b.gp, attached: b.gp + LIFE * RETAINER.gp, blended: b.gp + ATTACH * LIFE * RETAINER.gp };
}

// ------------------------------------------------------------------- reporting

const money = n => '$' + Math.round(n).toLocaleString('en-US');
const pct = (n, d = 0) => (n * 100).toFixed(d) + '%';
const band = (a, f) => f(a[0]) + '–' + f(a[1]);

function heading(s) { console.log('\n' + s + '\n' + '-'.repeat(s.length)); }

heading('Hardware, priced by the live engine (' + P.asOf + ')');
console.log('line'.padEnd(30) + 'customer pays'.padStart(18) + 'gross profit'.padStart(16) +
            'GM'.padStart(12) + 'hrs'.padStart(5) + '$/hour'.padStart(14));
for (const k of Object.keys(BUILDS)) {
  const h = hardware(k);
  console.log(h.label.padEnd(30) + band(h.total, money).padStart(18) + band(h.gp, money).padStart(16) +
              band(h.gm, x => pct(x)).padStart(12) + String(h.hours).padStart(5) +
              band(h.perHour, money).padStart(14));
}

heading('What one new customer buys first');
const b = blend();
b.rows.forEach(r => console.log('  ' + r.what.padEnd(24) + pct(r.w).padStart(5) +
  '   rev ' + money(r.rev).padStart(9) + '   gp ' + money(r.gp).padStart(8) +
  '   ' + String(r.hours).padStart(4) + ' hrs'));
console.log('  ' + 'BLENDED'.padEnd(24) + '     ' + '   rev ' + money(b.rev).padStart(9) +
  '   gp ' + money(b.gp).padStart(8) + '   ' + b.hrs.toFixed(1).padStart(4) + ' hrs');
console.log('\n  One customer eventually costs ' + loadPerCustomer().toFixed(1) +
            ' delivery hours, retainer included.');

heading('Steady state at the planned split (outreach ' + pct(SALES_SHARE) +
        ', overhead ' + OVERHEAD_BASE_HOURS + 'h + ' + OVERHEAD_PER_CUSTOMER + 'h/customer)');
console.log('hrs'.padEnd(5) + 'close'.padEnd(7) + 'cust/mo'.padStart(8) + 'retainers'.padStart(11) +
            'overhead'.padStart(11) + 'delivery'.padStart(13) + '  binds on'.padEnd(12) +
            'revenue/yr'.padStart(13) + 'GP/yr'.padStart(13));
for (const H of CAPACITY) for (const c of CLOSE_RATES) {
  const x = capacity(H, c);
  console.log(String(H).padEnd(5) + pct(c).padEnd(7) + x.custPerMo.toFixed(2).padStart(8) +
    x.retainers.toFixed(1).padStart(11) +
    (x.overhead.toFixed(0) + 'h (' + pct(x.overhead / H) + ')').padStart(11) +
    (x.deliveryUsed.toFixed(0) + ' / ' + x.deliveryCap.toFixed(0)).padStart(13) +
    ('  ' + x.binding).padEnd(12) + money(x.revYr).padStart(13) + money(x.gpYr).padStart(13));
}

heading('The split that makes both ceilings bind at once');
for (const c of CLOSE_RATES) {
  console.log('  close ' + pct(c) + ':');
  for (const H of CAPACITY) {
    const sh = optimalSalesShare(c, H);
    const x = capacity(H, c, null, sh), base = capacity(H, c);
    console.log('    ' + String(H).padStart(3) + 'h  outreach ' + pct(sh, 1).padStart(5) + ' = ' +
      x.sales.toFixed(1).padStart(5) + ' hrs  ' +
      x.custPerMo.toFixed(2) + ' cust/mo  ' + money(x.revYr).padStart(11) +
      '  vs planned ' + (x.revYr >= base.revYr ? '+' : '') + pct(x.revYr / base.revYr - 1));
  }
}

heading('What the fixed overhead base costs (140 hrs, planned split)');
for (const b of [8, 12, 20, 30]) {
  const lo = capacity(140, 0.15, b), hi = capacity(140, 0.25, b);
  console.log('  base ' + String(b).padStart(2) + 'h/mo  delivery cap ' + lo.deliveryCap.toFixed(0).padStart(3) +
    'h   at 15% close ' + money(lo.revYr).padStart(11) + '   at 25% close ' + money(hi.revYr).padStart(11));
}
console.log('\n  Free while demand binds; straight off the top once it does not.');

heading('Acquisition, on gross profit');
const L = ltv();
console.log('  first engagement, blended   ' + money(L.entry));
console.log('  LTV, retainer attached      ' + money(L.attached));
console.log('  LTV, blended at ' + pct(ATTACH) + ' attach ' + money(L.blended));
console.log('  LTV, blended at 60% attach  ' + money(L.entry + 0.60 * LIFE * RETAINER.gp));
for (const c of CLOSE_RATES) {
  const cac = HOURS_PER_CUSTOMER_AT_15 * (0.15 / c) * HOUR;
  console.log('  close ' + pct(c) + ': CAC (time) ' + money(cac).padStart(8) +
              '   LTV/CAC ' + (L.blended / cac).toFixed(1) + 'x');
}

heading('Value of one hour');
const mid = a => (a[0] + a[1]) / 2;
console.log('  PC assembly       ' + money(mid(hardware('gaming').gp) / 6) + ' once');
console.log('  Appliance setup   ' + money((mid(hardware('strix').gp) / 6 + mid(hardware('spark').gp) / 7) / 2) + ' once');
console.log('  Retainer service  ' + money(RETAINER.gp / RETAINER.hours) + ' per month, while retained');
console.log('  Outreach          ' + band(CLOSE_RATES.map(c => L.blended / (HOURS_PER_CUSTOMER_AT_15 * (0.15 / c))), money) +
            ' in lifetime gross profit — while demand binds');

heading('Ramp against ' + pct(CHURN) + ' monthly churn');
[[0.5, 'half'], [0.75, 'three quarters'], [0.9, 'nine tenths']].forEach(([f, label]) => {
  console.log('  ' + label.padEnd(16) + 'of steady state at month ' +
    Math.round(Math.log(1 - f) / Math.log(1 - CHURN)));
});
