// ---------------------------------------------------------------- assumptions

const CARD = 0.029;   // card processing, charged on the WHOLE invoice
const LLM  = 0.05;    // LLM/API cost, software lines only
const HOUR = 150;     // founder hour, used to cost acquisition time

// Total working hours a month — all in, not billable. Overhead comes out of
// this before anything reaches a customer.
const CAPACITY = [120, 140, 160];

// Outreach is committed as hours a week, not as a share of the calendar,
// because that is how the discipline actually works: it is a standing block in
// the diary, not a percentage that flexes with how busy the month feels.
//
// Modelling it as a share hid the most important structural fact in this
// business. Outreach hours alone decide how many customers arrive; total hours
// only decide how much idle delivery capacity sits behind them. Once this
// number is fixed, working a longer week does not earn more money.
const OUTREACH_HOURS_PER_WEEK = 7.5;
const WEEKS_PER_MONTH = 52 / 12;
const OUTREACH_MONTHLY = OUTREACH_HOURS_PER_WEEK * WEEKS_PER_MONTH;

// Overhead is NOT a flat share of hours, and modelling it as one was wrong.
//
// Staying current in a field that moves quarterly, keeping the tooling alive,
// and general business admin cost roughly the same whether the week is half
// full or full. Quoting, invoicing and onboarding scale with customers, not
// with capacity. A flat 25% share was defensible at 70 hours a month, where it
// came to 17 hours. Carried to a genuine full-time 160, the same share asserts
// 40 hours a month of bookkeeping, which is not a real number — and every hour
// it invents comes straight out of delivery.
//
// Splitting it fixed the error and had a consequence worth noticing: at
// full-time capacity, overhead shrinks as a share, delivery capacity grows, and
// the funnel has to work harder to keep up with it.
const OVERHEAD_BASE_HOURS = 12;      // fixed monthly: learning, tooling, admin
const OVERHEAD_PER_CUSTOMER = 1.5;   // quoting, invoicing, onboarding

// Funnel. 14 hours of outreach and calls to land one customer at a 15% close
// rate, scaling inversely with the close rate. This is the single input that
// decides whether the business is short of customers or short of hours.
const HOURS_PER_CUSTOMER_AT_15 = 14;
const CLOSE_RATES = [0.15, 0.25];

const ATTACH = 0.40;                 // share of customers who take a retainer
const CHURN = 0.05;                  // monthly
const LIFE = 1 / CHURN;              // 20 months
const RETAINER = { price: 897, hours: 1.5, gp: 897 * (1 - LLM - CARD) };
// Fixed monthly cost. This was $55 — hosting and a domain — which described a
// side project, not a business whose product is running frontier models for
// people. Itemised so each line can be argued with separately, because a single
// blended number hides the ones that were forgotten rather than estimated.
//
// Every dollar here comes off gross profit every month, so it compounds through
// the entire ramp: an error of $500/month is roughly $9,000 of extra capital
// over an eighteen-month climb, not $500.
//
// ESTIMATES, not quotes. Replace them with real figures before this goes in
// front of anyone.
const FIXED_COSTS = {
  'Frontier model subscriptions': 500,  // multiple premium plans, top tier
  'Business internet':            150,  // symmetric; local-AI work moves large files
  'Business phone line':           60,
  'Automation platform seats':    100,  // Zapier/Make at a tier that permits client work
  'Accounting software':           50,
  'Liability + E&O insurance':    175,  // SEE NOTE BELOW
  'Vehicle and fuel, on-site':    200,  // North Texas service area, client visits
  'Hosting, database, domain':     45
};

// The insurance line is the one most likely to have been forgotten, and it is
// not optional in practice: professional/E&O cover is what stands between a bad
// afternoon on a client's server and a personal liability. Several of the
// customers this business is aimed at — law offices, clinics, CPA practices —
// will ask for a certificate of insurance before they let anyone touch a
// machine, so it gates the highest-value pillar as well as protecting it.

const FIXED_MONTHLY = Object.values(FIXED_COSTS).reduce((a, b) => a + b, 0);

// The salary this business has to replace, and the reason outside capital is
// needed at all. Everything above is steady state; a founder does not live in
// steady state, he lives through the ramp to it.
const OWNER_DRAW_ANNUAL = 125000;

// A W-2 salary and an owner's draw of the same number are not the same cost.
// Two things move against you the day you leave payroll:
//   - the employer half of FICA becomes yours, on top of the half you paid
//   - benefits that were an employer line item become a personal one
// Modelling the draw at a flat $125k understates what has to be earned to stand
// still. BENEFITS_MONTHLY is the real family cover figure, not an estimate.
const SE_TAX_UPLIFT = 0.0765;
const BENEFITS_MONTHLY = 1250;   // actual family cover, not an estimate

